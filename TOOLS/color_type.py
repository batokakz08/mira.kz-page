def subtype_prompt(family):
    rules = "\n".join(
        "- " + name + ": " + rule + ";"
        for name, rule in SUBTYPE_RULES.items()
        if SUBTYPE_FAMILY[name] == family
    )
    return f"""Ты эксперт по 16-сезонной системе цветотипов. Семейство уже определено по фото: «{family}».
Посмотри на фото ещё раз и выбери ОДИН подтип только из этого семейства.

Подтипы семейства «{family}»:
{rules}

Выбирай по трём осям: светлота, насыщенность, температура. Если внешность на границе,
выбери основной подтип и укажи second_choice — второй ближайший подтип из этого же списка.
Учитывай, что свет на фото может искажать цвет. Если фото тёмное, размытое или лицо закрыто —
поставь confidence "низкая". Не комментируй тело, возраст или здоровье.

Ответь ТОЛЬКО JSON без пояснений и без markdown. Строго используй названия из списка:
{{"color_type":"название подтипа из списка","second_choice":"другое название из списка или пустая строка","reason":"1-2 предложения по-русски, почему","confidence":"высокая, средняя или низкая"}}"""


def main():
    parser = argparse.ArgumentParser(description="Find a colour type from a selfie and save profile.json.")
    parser.add_argument("photo", help="path to a selfie in daylight")
    parser.add_argument(
        "--out",
        default=str(Path(__file__).resolve().parent.parent / "profile.json"),
        help="where to save the profile (default: project profile.json)",
    )
    args = parser.parse_args()

    photo = image_part(args.photo)
    family_message = {
        "role": "user",
        "content": [{"type": "text", "text": FAMILY_PROMPT}, photo],
    }
    family_answer = chat([family_message], max_tokens=4000, thinking=True)
    family_data = parse_json(family_answer)
    if isinstance(family_data, list):
        family_data = family_data[0] if family_data else None
    if not isinstance(family_data, dict):
        raise SystemExit("The model did not return a family profile:\n" + family_answer[:800])

    raw_family = str(family_data.get("family", "")).strip().lower()
    family = raw_family if raw_family in FAMILY_PALETTES else next(
        (name for name in FAMILY_PALETTES if name in raw_family), None
    )
    if not family:
        raise SystemExit("Unknown family in the answer:\n" + family_answer[:800])

    subtype_message = {
        "role": "user",
        "content": [{"type": "text", "text": subtype_prompt(family)}, photo],
    }
    subtype_answer = chat([subtype_message], max_tokens=4000, thinking=True)
    subtype_data = parse_json(subtype_answer)
    if isinstance(subtype_data, list):
        subtype_data = subtype_data[0] if subtype_data else None
    if not isinstance(subtype_data, dict):
        raise SystemExit("The model did not return a subtype:\n" + subtype_answer[:800])

    raw_type = str(subtype_data.get("color_type", "")).strip().lower()
    color_type = raw_type if raw_type in PALETTES else LEGACY_TYPES.get(raw_type)
    if not color_type:
        color_type = next((name for name in PALETTES if name in raw_type), None)
    if not color_type or SUBTYPE_FAMILY[color_type] != family:
        raise SystemExit("The subtype does not belong to the family:\n" + subtype_answer[:800])

    raw_second = str(subtype_data.get("second_choice", "")).strip().lower()
    second = raw_second if raw_second in PALETTES else LEGACY_TYPES.get(raw_second, "")
    if second == color_type or (second and SUBTYPE_FAMILY[second] != family):
        second = ""
    confidences = [
        str(family_data.get("confidence", "")).strip().lower(),
        str(subtype_data.get("confidence", "")).strip().lower(),
    ]
    confidence = "низкая" if "низкая" in confidences else (
        subtype_data.get("confidence") or family_data.get("confidence", "")
    )

    profile = {
        "color_type": color_type,
        "family": family,
        "undertone": family_data.get("undertone", ""),
        "value": family_data.get("value", ""),
        "chroma": family_data.get("chroma", ""),
        "contrast": family_data.get("contrast", ""),
        "second_choice": second,
        "confidence": confidence,
        "style": family_data.get("style", "") or "универсальный",
        "reason": subtype_data.get("reason") or family_data.get("reason", ""),
        "palette": [{"hex": color, "name": name} for color, name in PALETTES[color_type]],
    }

    output = Path(args.out)
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(json.dumps(profile, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(json.dumps(profile, ensure_ascii=False, indent=2))
    print(f"Saved to {output}", file=sys.stderr)


if __name__ == "__main__":
    main()
